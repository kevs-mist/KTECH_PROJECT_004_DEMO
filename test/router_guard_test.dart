import 'package:flutter/material.dart';
import 'package:flutter_riverpod/flutter_riverpod.dart';
import 'package:flutter_test/flutter_test.dart';
import 'package:shared_preferences/shared_preferences.dart';
import 'package:ktech_project_004/app/router.dart';
import 'package:ktech_project_004/features/auth/auth_controller.dart';
import 'package:ktech_project_004/models/user_role.dart';

void main() {
  TestWidgetsFlutterBinding.ensureInitialized();

  setUp(() {
    SharedPreferences.setMockInitialValues({});
  });

  testWidgets('unauthenticated /dashboard redirects to /roles', (tester) async {
    tester.view.physicalSize = const Size(1280, 800);
    tester.view.devicePixelRatio = 1.0;
    addTearDown(tester.view.resetPhysicalSize);
    addTearDown(tester.view.resetDevicePixelRatio);

    final container = ProviderContainer();
    addTearDown(container.dispose);

    final router = createRouter(container: container, initialLocation: '/dashboard');

    await tester.pumpWidget(
      UncontrolledProviderScope(
        container: container,
        child: MaterialApp.router(
          routerConfig: router,
        ),
      ),
    );
    await tester.pumpAndSettle();

    expect(router.state.matchedLocation, '/roles');
  });

  testWidgets('doctor-role demo user visiting /admission redirects to /dashboard', (tester) async {
    tester.view.physicalSize = const Size(1280, 800);
    tester.view.devicePixelRatio = 1.0;
    addTearDown(tester.view.resetPhysicalSize);
    addTearDown(tester.view.resetDevicePixelRatio);

    final container = ProviderContainer();
    addTearDown(container.dispose);

    // Set demo doctor auth
    container.read(authControllerProvider.notifier).startDemo(
      role: UserRole.doctor,
      userName: 'Dr. Test',
    );

    final router = createRouter(container: container, initialLocation: '/admission');

    await tester.pumpWidget(
      UncontrolledProviderScope(
        container: container,
        child: MaterialApp.router(
          routerConfig: router,
        ),
      ),
    );
    await tester.pumpAndSettle();

    expect(router.state.matchedLocation, '/dashboard');
  });
}
